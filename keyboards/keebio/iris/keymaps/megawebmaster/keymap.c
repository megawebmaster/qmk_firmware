bool process_record_user(uint16_t keycode, keyrecord_t *record) {
  switch (keycode) {
    case BASE_LNX:
      if (record->event.pressed) {
        set_single_persistent_default_layer(_BASE_LNX);
      }
      return false;
    case LOW_LNX:
      if (record->event.pressed) {
        layer_on(_LOW_LNX);
      } else {
        layer_off(_LOW_LNX);
      }
      return false;
    case HI_LNX:
      if (record->event.pressed) {
        layer_on(_HI_LNX);
      } else {
        layer_off(_HI_LNX);
      }
      return false;
    case BASE_MOS:
      if (record->event.pressed) {
        set_single_persistent_default_layer(_BASE_MOS);
      }
      return false;
    case LOW_MOS:
      if (record->event.pressed) {
        layer_on(_LOW_MOS);
      } else {
        layer_off(_LOW_MOS);
      }
      return false;
    case HI_MOS:
      if (record->event.pressed) {
        layer_on(_HI_MOS);
      } else {
        layer_off(_HI_MOS);
      }
      return false;
    case LALT_T(KC_LCBR):
      if (record->event.pressed && record->tap.count) {
        tap_code16(KC_LCBR);
        return false;
      }
      break;
    case LCTL_T(KC_RCBR):
      if (record->event.pressed && record->tap.count) {
        tap_code16(KC_RCBR);
        return false;
      }
      break;
  }
  return true;
}
